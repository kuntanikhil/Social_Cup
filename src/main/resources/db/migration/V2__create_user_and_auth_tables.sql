CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    profile_photo_path VARCHAR(500),
    home_neighbourhood_id BIGINT,
    email_verified_at TIMESTAMPTZ,
    onboarding_completed_at TIMESTAMPTZ,
    account_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_home_neighbourhood
        FOREIGN KEY (home_neighbourhood_id) REFERENCES neighbourhoods (id)
);

CREATE INDEX idx_users_home_neighbourhood_id
    ON users (home_neighbourhood_id);

CREATE INDEX idx_users_account_status
    ON users (account_status);

CREATE TABLE auth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255),
    password_hash VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auth_identities_user_provider
        UNIQUE (user_id, provider),
    CONSTRAINT fk_auth_identities_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_auth_identities_provider
        CHECK (provider IN ('EMAIL', 'GOOGLE', 'APPLE')),
    CONSTRAINT chk_auth_identities_credentials
        CHECK (
            (provider = 'EMAIL' AND password_hash IS NOT NULL)
            OR
            (provider IN ('GOOGLE', 'APPLE') AND provider_user_id IS NOT NULL)
        )
);

CREATE INDEX idx_auth_identities_user_id
    ON auth_identities (user_id);

CREATE UNIQUE INDEX uq_auth_identities_provider_user_id
    ON auth_identities (provider, provider_user_id)
    WHERE provider_user_id IS NOT NULL;

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_refresh_tokens_expiry
        CHECK (expires_at > created_at),
    CONSTRAINT chk_refresh_tokens_revocation
        CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

CREATE INDEX idx_refresh_tokens_user_id
    ON refresh_tokens (user_id);

CREATE INDEX idx_refresh_tokens_expires_at
    ON refresh_tokens (expires_at);

