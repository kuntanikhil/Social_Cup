CREATE TABLE coffee_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_coffee_preferences_active
    ON coffee_preferences (active);

CREATE TABLE user_coffee_preferences (
    user_id BIGINT NOT NULL,
    coffee_preference_id BIGINT NOT NULL,
    CONSTRAINT pk_user_coffee_preferences
        PRIMARY KEY (user_id, coffee_preference_id),
    CONSTRAINT fk_user_coffee_preferences_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_coffee_preferences_preference
        FOREIGN KEY (coffee_preference_id) REFERENCES coffee_preferences (id)
);

CREATE INDEX idx_user_coffee_preferences_preference_id
    ON user_coffee_preferences (coffee_preference_id);
